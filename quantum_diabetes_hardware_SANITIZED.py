def metrics(y_true, y_pred):
    return {
        "accuracy" : round(accuracy_score (y_true, y_pred),                        4),
        "precision": round(precision_score(y_true, y_pred, zero_division=0),        4),
        "recall"   : round(recall_score   (y_true, y_pred),                        4),
        "f1"       : round(f1_score       (y_true, y_pred),                        4),
    }

def build_vqc(n_qubits=N_QUBITS, fm_reps=FM_REPS,
              ansatz_reps=BEST_REPS, maxiter=COBYLA_STEPS):
    """Fresh VQC on noiseless IBM Aer StatevectorSampler."""
    fm  = ZZFeatureMap(feature_dimension=n_qubits, reps=fm_reps)
    ans = RealAmplitudes(num_qubits=n_qubits, reps=ansatz_reps, entanglement="full")
    return VQC(
        num_qubits  = n_qubits,
        feature_map = fm,
        ansatz      = ans,
        optimizer   = COBYLA(maxiter=maxiter),
        sampler     = StatevectorSampler(),
    )

def build_noise_model():
    """
    IBM hardware noise model (ibm_brisbane / nairobi family).
    SQ error 0.30% | CX error 1.50% | Readout 2.0/2.5%.
    """
    nm = NoiseModel()
    sq_gates = ["u1", "u2", "u3", "x", "h", "sx", "rz", "id"]
    nm.add_all_qubit_quantum_error(depolarizing_error(HW_NOISE["sq_error"], 1), sq_gates)
    nm.add_all_qubit_quantum_error(depolarizing_error(HW_NOISE["cx_error"], 2), ["cx"])
    nm.add_all_qubit_readout_error(
        ReadoutError([[1 - HW_NOISE["ro_01"], HW_NOISE["ro_01"]],
                      [HW_NOISE["ro_10"],     1 - HW_NOISE["ro_10"]]])
    )
    return nm

def hw_predict(X_data, trained_vqc, noisy_backend, shots=SHOTS):
    """
    Simulate IBM hardware predictions.
    1. Bind trained weights + feature values into the VQC circuit.
    2. Add measurement, transpile to device basis gates.
    3. Run on noisy AerSimulator; majority-vote over 'shots' samples.
    Returns (predicted_labels, class-1 probabilities).
    """
    circ  = trained_vqc._neural_network._circuit
    cp    = sorted(circ.parameters, key=lambda p: p.name)
    ip    = [p for p in cp if "input"  in p.name]
    wp    = [p for p in cp if "weight" in p.name]
    ws    = trained_vqc.weights

    preds, probs = [], []
    for x in X_data:
        bd = {**{p: float(x[i])  for i, p in enumerate(ip)},
              **{p: float(ws[i]) for i, p in enumerate(wp)}}
        bound  = circ.assign_parameters(bd)
        bound.measure_all()
        tc     = transpile(bound, noisy_backend, optimization_level=1)
        counts = noisy_backend.run(tc, shots=shots).result().get_counts()
        total  = sum(counts.values())
        p1     = sum(v for k, v in counts.items()
                     if k.replace(" ", "")[-1] == "1") / total
        preds.append(1 if p1 >= 0.5 else 0)
        probs.append(p1)
    return np.array(preds), np.array(probs)

