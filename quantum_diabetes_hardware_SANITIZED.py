mcnemar_results = {}

def mcnemar_test(key_a, key_b):
    ya = RESULTS[key_a]["y_pred"]
    yb = RESULTS[key_b]["y_pred"]
    # Contingency table
    # b = A correct,  B wrong
    # c = A wrong,    B correct
    b = int(np.sum((ya == y_te) & (yb != y_te)))
    c = int(np.sum((ya != y_te) & (yb == y_te)))
    table = [[int(np.sum((ya == y_te) & (yb == y_te))), b],
             [c,  int(np.sum((ya != y_te) & (yb != y_te)))]]
    result = mcnemar(table, exact=True)
    p = round(float(result.pvalue), 6)
    sig = "* SIGNIFICANT" if p < 0.05 else "  not significant"
    la, lb = STYLE[key_a][1], STYLE[key_b][1]
    print(f"    {la:<26} vs {lb:<26}  b={b}  c={c}  p={p:.6f}  {sig}")
    return {"b": b, "c": c, "p_value": p,
            "significant": p < 0.05, "table": table}

