print("\n  [4A] Bootstrap 95% CIs (n_boot=2000)...")

N_BOOT = 2000
CI_ALPHA = 0.05

def bootstrap_ci(y_true, y_pred, y_prob=None, n_boot=N_BOOT, seed=SEED):
    """
    Returns {metric: (mean, lower_95, upper_95)} for all standard metrics.
    Uses the percentile method; invalid resamples (single-class) are skipped.
    """
    rng_b = np.random.default_rng(seed)
    scores = {k: [] for k in ["accuracy","precision","recall","f1","roc_auc"]}
    n = len(y_true)
    for _ in range(n_boot):
        idx = rng_b.integers(0, n, size=n)
        yt, yp = y_true[idx], y_pred[idx]
        if len(np.unique(yt)) < 2:      # skip unbalanced resamples
            continue
        scores["accuracy"].append(accuracy_score(yt, yp))
        scores["precision"].append(precision_score(yt, yp, zero_division=0))
        scores["recall"].append(recall_score(yt, yp, zero_division=0))
        scores["f1"].append(f1_score(yt, yp, zero_division=0))
        if y_prob is not None:
            ypr = y_prob[idx]
            try:
                scores["roc_auc"].append(roc_auc_score(yt, ypr))
            except Exception:
                pass
        else:
            scores["roc_auc"].append(roc_auc_score(yt, yp))
    result = {}
    for k, vals in scores.items():
        if not vals:
            result[k] = (np.nan, np.nan, np.nan)
            continue
        arr = np.array(vals)
        lo  = np.percentile(arr, 100 * CI_ALPHA / 2)
        hi  = np.percentile(arr, 100 * (1 - CI_ALPHA / 2))
        result[k] = (round(float(np.mean(arr)), 4),
                     round(float(lo), 4),
                     round(float(hi), 4))
    return result

